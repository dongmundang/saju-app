const YAONAME = ['초효', '2효', '3효', '4효', '5효', '상효'];

// 동전 3개 던지기 → 6/7/8/9
function tossLine() {
  let sum = 0;
  for (let i = 0; i < 3; i++) sum += (Math.random() < 0.5 ? 2 : 3);
  return sum; // 6,7,8,9
}

// lines: 아래→위 6개, 각 6/7/8/9
function castHexagram(lines) {
  if (!lines || lines.length !== 6) lines = Array.from({ length: 6 }, tossLine);
  const primaryBits = lines.map(v => (v === 7 || v === 9) ? '1' : '0').join('');
  const changing = lines.map((v, i) => (v === 6 || v === 9) ? i : -1).filter(i => i >= 0);
  const changedBits = lines.map(v => {
    if (v === 6) return '1'; // 노음 → 양
    if (v === 9) return '0'; // 노양 → 음
    return (v === 7) ? '1' : '0';
  }).join('');

  const p = HEX[primaryBits];
  const c = changing.length ? HEX[changedBits] : null;

  return {
    lines,
    changingYao: changing.map(i => YAONAME[i]),
    primary: { num: p[0], name: p[1], meaning: p[2], bits: primaryBits },
    changed: c ? { num: c[0], name: c[1], meaning: c[2], bits: changedBits } : null
  };
}

function buildIchingPrompt(question, cast) {
  const chg = cast.changingYao.length
    ? `변효: ${cast.changingYao.join(', ')} → 변괘 ${cast.changed.name}(${cast.changed.num}번): ${cast.changed.meaning}`
    : '변효 없음 (본괘로만 판단)';
  return `주역 점을 풀이해 주세요.

질문: ${question || '(질문 없음 - 현재 상황 전반)'}

본괘: ${cast.primary.name} (${cast.primary.num}번)
본괘 뜻: ${cast.primary.meaning}
${chg}

당신은 주역에 정통한 상담가입니다. 아래 항목으로, 각 제목(###)을 그대로 써서 충분히 풀어 답하세요.

### 뽑힌 괘
본괘 "${cast.primary.name}"이 어떤 상(象)인지 쉬운 말로 그려주고, 이 괘가 나온 것이 질문에 대해 무엇을 시사하는지. (4~5문장)

### 지금의 형세
본괘가 말하는 현재 상황 — 무엇이 순조롭고 무엇이 막혀 있는지, 지금 어느 자리에 서 있는지. (4~5문장)

### 흐름과 변화
${cast.changingYao.length ? `변효(${cast.changingYao.join(', ')})와 변괘 "${cast.changed.name}"가 가리키는 변화의 방향 — 무엇이 어떻게 바뀌어 가는지, 그 변화를 어떻게 맞아야 하는지` : '변효가 없으니 본괘가 그대로 유지되는 상황 — 지금의 태도를 어떻게 지켜야 하는지'}. (5~6문장)

### 질문에 대한 답
질문에 대해 "그렇다 / 아니다 / 아직 때가 아니다 / 조건부로 가능하다" 중 하나로 방향을 분명히 제시하고, 괘의 어느 부분이 그렇게 말하는지 근거를 들어 설명. (4~5문장)

### 실천 조언
지금 이 사람이 하면 좋은 것과 삼가야 할 것을 구체적으로 2~3가지.

규칙: 괘와 변효의 뜻에 근거해서만 말하고 지어내지 말 것, 겁주지 말고 방향을 제시할 것, 전부 한국어.
마지막에 "※ 주역은 지금 이 순간의 기운을 비추는 거울입니다. 마음을 정하는 참고로 삼으세요." 를 덧붙이세요.`;
}

